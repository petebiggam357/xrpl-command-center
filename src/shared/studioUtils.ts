// Track 2: Ledger Hardware Wallet WebHID APDU Framing (XRP App BIP-44 44'/144')
// ============================================================================

export function encodeBip32Path(pathStr = "44'/144'/0'/0/0"): Uint8Array {
  const parts = pathStr
    .replace(/^m\//i, '')
    .split('/')
    .filter(Boolean);
  const buf = new Uint8Array(1 + parts.length * 4);
  buf[0] = parts.length;
  const view = new DataView(buf.buffer);
  for (let i = 0; i < parts.length; i++) {
    const hardened = parts[i].endsWith("'") || parts[i].toLowerCase().endsWith('h');
    const num = parseInt(parts[i].replace(/['hH]$/, ''), 10);
    if (!Number.isFinite(num) || num < 0) {
      throw new Error(`Invalid BIP-32 path segment "${parts[i]}"`);
    }
    const val = ((hardened ? 0x80000000 : 0) | num) >>> 0;
    view.setUint32(1 + i * 4, val, false);
  }
  return buf;
}

export function buildLedgerGetAddressApdu(
  bip32Path = "44'/144'/0'/0/0",
  displayOnDevice = false
): Uint8Array {
  const pathBytes = encodeBip32Path(bip32Path);
  const apdu = new Uint8Array(5 + pathBytes.length);
  apdu[0] = 0xe0; // CLA
  apdu[1] = 0x02; // INS_GET_PUBLIC_KEY
  apdu[2] = displayOnDevice ? 0x01 : 0x00; // P1
  apdu[3] = 0x00; // P2 (secp256k1 default curve on Ledger XRP app)
  apdu[4] = pathBytes.length;
  apdu.set(pathBytes, 5);
  return apdu;
}

export function buildLedgerSignTxApdus(
  bip32Path: string,
  signingTxHex: string
): Uint8Array[] {
  const cleanHex = signingTxHex.trim().replace(/^0x/i, '');
  if (cleanHex.length % 2 !== 0 || !/^[0-9A-Fa-f]+$/.test(cleanHex)) {
    throw new Error('Invalid signing hex payload for Ledger APDU');
  }
  const txBytes = new Uint8Array(cleanHex.length / 2);
  for (let i = 0; i < txBytes.length; i++) {
    txBytes[i] = parseInt(cleanHex.slice(i * 2, i * 2 + 2), 16);
  }

  const pathBytes = encodeBip32Path(bip32Path);
  const fullPayload = new Uint8Array(pathBytes.length + txBytes.length);
  fullPayload.set(pathBytes, 0);
  fullPayload.set(txBytes, pathBytes.length);

  const MAX_CHUNK = 150;
  const chunks: Uint8Array[] = [];
  for (let offset = 0; offset < fullPayload.length; offset += MAX_CHUNK) {
    chunks.push(fullPayload.slice(offset, Math.min(fullPayload.length, offset + MAX_CHUNK)));
  }

  return chunks.map((chunk, idx) => {
    const isFirst = idx === 0;
    const isLast = idx === chunks.length - 1;
    let p1 = 0x01; // middle
    if (isFirst && isLast) p1 = 0x00;
    else if (isFirst) p1 = 0x80;
    else if (isLast) p1 = 0x81;

    const apdu = new Uint8Array(5 + chunk.length);
    apdu[0] = 0xe0; // CLA
    apdu[1] = 0x04; // INS_SIGN
    apdu[2] = p1;
    apdu[3] = 0x00; // P2
    apdu[4] = chunk.length;
    apdu.set(chunk, 5);
    return apdu;
  });
}

export function frameHidPackets(apdu: Uint8Array, channel = 0x0101): Uint8Array[] {
  const PACKET_SIZE = 64;
  const frames: Uint8Array[] = [];
  let offset = 0;
  let seq = 0;

  while (offset < apdu.length) {
    const packet = new Uint8Array(PACKET_SIZE);
    packet[0] = (channel >> 8) & 0xff;
    packet[1] = channel & 0xff;
    packet[2] = 0x05; // TAG_APDU
    packet[3] = (seq >> 8) & 0xff;
    packet[4] = seq & 0xff;

    let pos = 5;
    if (seq === 0) {
      packet[5] = (apdu.length >> 8) & 0xff;
      packet[6] = apdu.length & 0xff;
      pos = 7;
    }

    const copyLen = Math.min(PACKET_SIZE - pos, apdu.length - offset);
    packet.set(apdu.subarray(offset, offset + copyLen), pos);
    offset += copyLen;
    seq += 1;
    frames.push(packet);
  }
  return frames;
}

