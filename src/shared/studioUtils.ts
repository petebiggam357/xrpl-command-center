// Track 3: XLS-30 AMM Constant-Product (x * y = k) Simulator & Slippage Math
// ============================================================================

export interface AmmSwapSimulation {
  spotPrice: number; // ReserveOut per 1 ReserveIn
  effectivePrice: number;
  amountOut: number;
  minOutWithSlippage: number;
  priceImpactPct: number;
  feePaidIn: number;
  newReserveIn: number;
  newReserveOut: number;
}

export function simulateAmmConstantProductSwap(params: {
  reserveIn: number;
  reserveOut: number;
  amountIn: number;
  tradingFeeBps: number; // e.g. 30 bps = 0.30%
  slippagePct: number; // e.g. 0.5 = 0.5%
}): AmmSwapSimulation {
  const { reserveIn, reserveOut, amountIn, tradingFeeBps, slippagePct } = params;
  if (reserveIn <= 0 || reserveOut <= 0 || amountIn <= 0) {
    return {
      spotPrice: reserveIn > 0 ? reserveOut / reserveIn : 0,
      effectivePrice: 0,
      amountOut: 0,
      minOutWithSlippage: 0,
      priceImpactPct: 0,
      feePaidIn: 0,
      newReserveIn: reserveIn,
      newReserveOut: reserveOut,
    };
  }

  const feeFraction = Math.max(0, Math.min(0.01, tradingFeeBps / 10_000));
  const feePaidIn = amountIn * feeFraction;
  const netIn = amountIn - feePaidIn;
  const k = reserveIn * reserveOut;
  const newReserveIn = reserveIn + netIn;
  const newReserveOut = k / newReserveIn;
  const amountOut = Math.max(0, reserveOut - newReserveOut);
  const spotPrice = reserveOut / reserveIn;
  const effectivePrice = amountOut / amountIn;
  const idealOutNoFee = amountIn * spotPrice;
  const priceImpactPct =
    idealOutNoFee > 0 ? Math.max(0, ((idealOutNoFee - amountOut) / idealOutNoFee) * 100) : 0;
  const minOutWithSlippage = amountOut * Math.max(0, 1 - slippagePct / 100);

  return {
    spotPrice,
    effectivePrice,
    amountOut,
    minOutWithSlippage,
    priceImpactPct,
    feePaidIn,
    newReserveIn: reserveIn + amountIn,
    newReserveOut,
  };
}

