export interface DiffLine {
  type: 'same' | 'added' | 'removed';
  text: string;
  oldLineNo?: number;
  newLineNo?: number;
}

/**
 * Compute a clean LCS line-by-line unified diff (bounded for config files).
 */
export function computeUnifiedLineDiff(beforeText: string, afterText: string): DiffLine[] {
  const a = beforeText.replace(/\r\n/g, '\n').split('\n');
  const b = afterText.replace(/\r\n/g, '\n').split('\n');
  const m = a.length;
  const n = b.length;

  // Guard for very large files (>900 lines)
  if (m * n > 810_000) {
    const out: DiffLine[] = [];
    const max = Math.max(m, n);
    for (let i = 0; i < max; i++) {
      if (a[i] === b[i]) {
        out.push({ type: 'same', text: a[i], oldLineNo: i + 1, newLineNo: i + 1 });
      } else {
        if (i < m) out.push({ type: 'removed', text: a[i], oldLineNo: i + 1 });
        if (i < n) out.push({ type: 'added', text: b[i], newLineNo: i + 1 });
      }
    }
    return out;
  }

  const dp: Uint16Array[] = Array.from({ length: m + 1 }, () => new Uint16Array(n + 1));
  for (let i = m - 1; i >= 0; i--) {
    for (let j = n - 1; j >= 0; j--) {
      if (a[i] === b[j]) {
        dp[i][j] = dp[i + 1][j + 1] + 1;
      } else {
        dp[i][j] = Math.max(dp[i + 1][j], dp[i][j + 1]);
      }
    }
  }

  const result: DiffLine[] = [];
  let i = 0;
  let j = 0;
  while (i < m && j < n) {
    if (a[i] === b[j]) {
      result.push({ type: 'same', text: a[i], oldLineNo: i + 1, newLineNo: j + 1 });
      i++;
      j++;
    } else if (dp[i + 1][j] >= dp[i][j + 1]) {
      result.push({ type: 'removed', text: a[i], oldLineNo: i + 1 });
      i++;
    } else {
      result.push({ type: 'added', text: b[j], newLineNo: j + 1 });
      j++;
    }
  }
  while (i < m) {
    result.push({ type: 'removed', text: a[i], oldLineNo: i + 1 });
    i++;
  }
  while (j < n) {
    result.push({ type: 'added', text: b[j], newLineNo: j + 1 });
    j++;
  }
  return result;
}

