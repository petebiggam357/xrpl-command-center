// Track 5: Safe RFC-4180 CSV Serializer (with Spreadsheet Formula Injection Guard)
// ============================================================================

export function serializeRowsToCsv(
  headers: string[],
  rows: Array<Array<string | number | boolean | null | undefined>>
): string {
  const escapeCell = (val: string | number | boolean | null | undefined): string => {
    if (val === null || val === undefined) return '';
    let str = String(val);
    // Guard against CSV spreadsheet formula injection (=, +, -, @) for non-numeric strings
    if (/^[=+\-@]/.test(str) && !/^-\d+(\.\d+)?$/.test(str)) {
      str = `'${str}`;
    }
    if (/[",\r\n]/.test(str)) {
      return `"${str.replace(/"/g, '""')}"`;
    }
    return str;
  };

  const out = [headers.map(escapeCell).join(',')];
  for (const row of rows) {
    out.push(row.map(escapeCell).join(','));
  }
  return out.join('\n') + '\n';
}
