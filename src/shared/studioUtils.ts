export interface XrpLedgerTomlInput {
  domain: string;
  orgName: string;
  orgEmail?: string;
  issuerAddress?: string;
  validatorPubKey?: string;
  network?: NetworkId;
  currencyCode?: string;
  currencyName?: string;
  currencyDesc?: string;
}

export function generateXrpLedgerToml(input: XrpLedgerTomlInput): string {
  const isoDate = new Date(Date.now() + 365 * 86_400_000).toISOString();
  const lines: string[] = [
    '# Generated by XRPL Command Center — Host at https://' +
      (input.domain.trim() || 'example.com') +
      '/.well-known/xrp-ledger.toml',
    '# Ensure CORS header `Access-Control-Allow-Origin: *` is served.',
    '',
    '[METADATA]',
    `modified = ${new Date().toISOString()}`,
    `expires = ${isoDate}`,
    '',
    '[[PRINCIPALS]]',
    `name = "${(input.orgName || 'Organization').replace(/"/g, '')}"`,
  ];
  if (input.orgEmail?.trim()) {
    lines.push(`email = "${input.orgEmail.trim().replace(/"/g, '')}"`);
  }

  if (input.validatorPubKey?.trim()) {
    lines.push(
      '',
      '[[VALIDATORS]]',
      `public_key = "${input.validatorPubKey.trim()}"`,
      `network = "${input.network === 'testnet' ? 'testnet' : 'main'}"`
    );
  }

  if (input.issuerAddress?.trim()) {
    lines.push(
      '',
      '[[ACCOUNTS]]',
      `address = "${input.issuerAddress.trim()}"`,
      `network = "${input.network === 'testnet' ? 'testnet' : 'main'}"`,
      `desc = "Official Issuing / Treasury Account"`
    );
  }

  if (input.currencyCode?.trim() && input.issuerAddress?.trim()) {
    lines.push(
      '',
      '[[CURRENCIES]]',
      `code = "${input.currencyCode.trim()}"`,
      `issuer = "${input.issuerAddress.trim()}"`,
      `network = "${input.network === 'testnet' ? 'testnet' : 'main'}"`,
      `name = "${(input.currencyName || input.currencyCode).trim().replace(/"/g, '')}"`,
      `desc = "${(input.currencyDesc || '').trim().replace(/"/g, '')}"`
    );
  }

  return lines.join('\n') + '\n';
}

export function validateXrpLedgerToml(tomlText: string): {
  valid: boolean;
  sectionsFound: string[];
  issues: string[];
} {
  const issues: string[] = [];
  const sectionsFound: string[] = [];
  const lines = tomlText.split(/\r?\n/);

  for (let idx = 0; idx < lines.length; idx++) {
    const raw = lines[idx].trim();
    if (!raw || raw.startsWith('#')) continue;

    const secMatch = raw.match(/^\[(\[?[A-Z0-9_]+\]?)\]$/);
    if (secMatch) {
      sectionsFound.push(secMatch[0]);
      continue;
    }

    const kvMatch = raw.match(/^[A-Za-z0-9_-]+\s*=\s*.+$/);
    if (!kvMatch) {
      issues.push(`Line ${idx + 1}: Unrecognized TOML key/value syntax: "${raw.slice(0, 40)}"`);
    }
  }

  if (sectionsFound.length === 0) {
    issues.push('No TOML sections found (expected [METADATA], [[ACCOUNTS]], [[VALIDATORS]], or [[CURRENCIES]]).');
  }
  if (/address\s*=\s*"([^"]+)"/.test(tomlText)) {
    const matches = tomlText.matchAll(/address\s*=\s*"([^"]+)"/g);
    for (const m of matches) {
      if (!/^r[1-9A-HJ-NP-Za-km-z]{24,34}$/.test(m[1])) {
        issues.push(`Invalid XRPL classic r-address in [[ACCOUNTS]]: "${m[1]}"`);
      }
    }
  }

  return {
    valid: issues.length === 0,
    sectionsFound: Array.from(new Set(sectionsFound)),
    issues,
  };
}

